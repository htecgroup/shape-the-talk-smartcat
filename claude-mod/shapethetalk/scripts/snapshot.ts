// Renders the sample boards as plain text (the terminal renderer's glyphs) into SNAPSHOT.md.
// Run: node scripts/snapshot.ts   (Node 23.6+ runs TypeScript directly)

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { fullLayout } from '../hooks/layout.ts'
import { renderGrid, snapshotText } from '../hooks/grid.ts'
import { SAMPLES, boardFrom } from './samples.ts'

const here = dirname(fileURLToPath(import.meta.url))
const WIDTHS = [120, 70, 48]
const out: string[] = [
  '# ShapeTheTalk terminal snapshots',
  '',
  'Generated by `node scripts/snapshot.ts` from the boards in `scripts/samples.ts`: the glyphs the terminal pane draws where it shows no pictures, or with `/diagram look grid` (colours left out; kitty and Ghostty get the hand-drawn PNG, see `node scripts/still.ts`), at a few pane widths. A drawing wider than the pane pans with the ◀ ▶ buttons.',
  '',
]
for (const s of SAMPLES) {
  const board = boardFrom(s.ops)
  const placement = fullLayout(board)
  for (const columns of WIDTHS) {
    const g = renderGrid(board, placement, { columns })
    out.push(`## ${s.name} · ${columns} columns`, '')
    out.push(`${Object.keys(board.nodes).length} nodes, ${Object.keys(board.edges).length} edges; drawn ${g.dir}, ${g.width}×${g.height} cells${g.undrawn.length ? `; ${g.undrawn.length} edge(s) not drawn` : ''}`, '')
    out.push('```', snapshotText(g), '```', '')
  }
}
const file = join(here, '..', 'SNAPSHOT.md')
writeFileSync(file, out.join('\n'))
console.log(`wrote ${file}`)
